PREFIX = ["", "please ", "can you ", "could you ", "i want to ", "kindly ", "hey "]
SUFFIX = ["", " please", " for me", " thanks"]


def typo(text: str, rng: random.Random) -> str:
    words = text.split()
    i = rng.randrange(len(words))
    w = words[i]
    if len(w) > 4 and not w.startswith("_"):
        j = rng.randrange(1, len(w) - 1)
        words[i] = w[:j] + w[j + 1 :] if rng.random() < 0.5 else w[:j] + w[j + 1] + w[j] + w[j + 2 :]
    return " ".join(words)


def seed_examples() -> list[tuple[str, str]]:
    rng = random.Random(7)
    out = []
    for intent, temps in TEMPLATES.items():
        for t in temps:
            out.append((t, intent))
            for _ in range(2):
                out.append((f"{rng.choice(PREFIX)}{t}{rng.choice(SUFFIX)}".strip(), intent))
            out.append((typo(t, rng), intent))
    return list(dict.fromkeys(out))
